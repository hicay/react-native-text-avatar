// Regenerates src/noise.ts: a small tileable film-grain PNG, embedded as a data URI
// so the gradient avatar needs no asset pipeline. Run: node scripts/noise.js
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const SIZE = 64;
let seed = 0x2f6e2b1;
const rand = () => {
  seed = (seed + 0x6d2b79f5) >>> 0;
  let t = seed;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};

// Grayscale + alpha, one filter byte per row.
const raw = Buffer.alloc(SIZE * (1 + SIZE * 2));
for (let y = 0; y < SIZE; y += 1) {
  for (let x = 0; x < SIZE; x += 1) {
    const i = y * (1 + SIZE * 2) + 1 + x * 2;
    raw[i] = rand() < 0.5 ? 0 : 255;
    raw[i + 1] = Math.floor(rand() * rand() * 150);
  }
}

const chunk = (type, data) => {
  const body = Buffer.concat([Buffer.from(type), data]);
  const out = Buffer.alloc(body.length + 8);
  out.writeUInt32BE(data.length, 0);
  body.copy(out, 4);
  out.writeUInt32BE(zlib.crc32(body) >>> 0, body.length + 4);
  return out;
};
const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(SIZE, 0);
ihdr.writeUInt32BE(SIZE, 4);
ihdr[8] = 8; // bit depth
ihdr[9] = 4; // grayscale with alpha
const png = Buffer.concat([
  Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
  chunk('IHDR', ihdr),
  chunk('IDAT', zlib.deflateSync(raw, { level: 9 })),
  chunk('IEND', Buffer.alloc(0)),
]);

fs.writeFileSync(
  path.join(__dirname, '..', 'src', 'noise.ts'),
  `// Generated by scripts/noise.js. Do not edit.\nexport const NOISE_SIZE = ${SIZE};\nexport const NOISE_URI: string =\n  'data:image/png;base64,${png.toString('base64')}';\n`
);
console.log('noise.ts:', png.length, 'bytes png');
